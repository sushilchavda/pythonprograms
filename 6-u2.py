
print("--- Iterating over List ---")

fruits = ["Apple", "Banana", "Mango"]

for fruit in fruits:
    print(fruit)

print("\n--- Iterating over String ---")

text = "Python"

for character in text:
    print(character)

print("\n--- Iterating over Dictionary ---")

student = {
    "Name": "Sushil",
    "Age": 20,
    "Course": "Python"
}

for key, value in student.items():
    print(key, ":", value)
