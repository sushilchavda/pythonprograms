text = "PythonProgramming"

print("--- 1. String Slicing Demo ---")
print(f"Original Text: {text}")
print(f"Slice [0:6] (First 6 characters): {text[0:6]}")
print(f"Slice [6:] (From index 6 to end): {text[6:]}")
print(f"Slice [:6] (Up to index 6): {text[:6]}")
print(f"Slice [-7:] (Last 7 characters): {text[-7:]}")
print(f"Slice [::2] (Every second character): {text[::2]}")
print(f"Slice [::-1] (Reverse the entire string): {text[::-1]}")
print()
