# Program: Mathematical Operations using math module

import math

a = 25
b = 4

print("Square Root of a :", math.sqrt(a))
print("Power of a and b :", math.pow(a, b))
print("Factorial of b   :", math.factorial(b))
print("Ceiling of 4.3   :", math.ceil(4.3))
print("Floor of 4.7     :", math.floor(4.7))
print("Absolute value   :", math.fabs(-10))
print("Value of Pi      :", math.pi)
print("Value of e       :", math.e)
print("GCD of a and b   :", math.gcd(a, b))
